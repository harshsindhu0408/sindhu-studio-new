/**
 * Turns camera originals into web-ready images.
 *
 *   originals/*.JPG  ──►  public/images/work/<slug>.webp   (max 2400px, ~300–600 KB)
 *                    ──►  src/data/media.generated.ts      (typed manifest with blur placeholders)
 *
 * Descriptions live in scripts/media-manifest.json (slug, category, alt, featured).
 * Originals stay out of git and are never served.
 *
 * Usage: npm run images
 */
import { readdir, readFile, writeFile, mkdir, stat } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const SRC_DIR = path.join(ROOT, "originals");
const OUT_DIR = path.join(ROOT, "public/images/work");
const MANIFEST = path.join(ROOT, "scripts/media-manifest.json");
const TS_OUT = path.join(ROOT, "src/data/media.generated.ts");

const MAX_EDGE = 2400;
const QUALITY = 78;
const COPYRIGHT = `© ${new Date().getFullYear()} Sindhu Studio, Rohtak. All rights reserved.`;

async function exists(p) {
    try {
        await stat(p);
        return true;
    } catch {
        return false;
    }
}

const manifest = (await exists(MANIFEST)) ? JSON.parse(await readFile(MANIFEST, "utf8")) : {};
await mkdir(OUT_DIR, { recursive: true });

const files = (await readdir(SRC_DIR)).filter((f) => /\.(jpe?g|png|tiff?)$/i.test(f)).sort();
const entries = [];
let totalBytes = 0;

for (const file of files) {
    const meta = manifest[file] ?? {};
    const slug = meta.slug ?? path.parse(file).name.toLowerCase().replace(/[^a-z0-9]+/g, "-");
    const outFile = path.join(OUT_DIR, `${slug}.webp`);

    // .rotate() applies EXIF orientation; withMetadata is not used, so GPS/camera EXIF is stripped.
    const pipeline = sharp(path.join(SRC_DIR, file)).rotate();
    const { data, info } = await pipeline
        .clone()
        .resize({ width: MAX_EDGE, height: MAX_EDGE, fit: "inside", withoutEnlargement: true })
        .webp({ quality: QUALITY, effort: 5 })
        .withExif({ IFD0: { Copyright: COPYRIGHT, Artist: "Sindhu Studio" } })
        .toBuffer({ resolveWithObject: true });
    await writeFile(outFile, data);
    totalBytes += data.length;

    const blur = await pipeline
        .clone()
        .resize(16, 16, { fit: "inside" })
        .webp({ quality: 40 })
        .toBuffer();

    entries.push({
        id: slug,
        file,
        src: `/images/work/${slug}.webp`,
        width: info.width,
        height: info.height,
        blurDataURL: `data:image/webp;base64,${blur.toString("base64")}`,
        category: meta.category ?? "wedding",
        alt: meta.alt ?? "Wedding photograph by Sindhu Studio, Rohtak",
        featured: Boolean(meta.featured),
    });
    console.log(`✓ ${file.padEnd(20)} → ${slug}.webp  ${info.width}×${info.height}  ${(data.length / 1024).toFixed(0)} KB`);
}

const ts = `// AUTO-GENERATED by scripts/optimize-images.mjs. Do not edit by hand.
// Edit scripts/media-manifest.json and run \`npm run images\` instead.
import type { MediaItem } from "./media";

export const mediaItems: MediaItem[] = ${JSON.stringify(
    entries.map(({ file: _file, ...rest }) => rest),
    null,
    2,
)};
`;
await writeFile(TS_OUT, ts);
console.log(`\n${entries.length} images · ${(totalBytes / 1024 / 1024).toFixed(1)} MB total → ${path.relative(ROOT, OUT_DIR)}`);
